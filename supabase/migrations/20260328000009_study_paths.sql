-- 升学专项：学科 → 考研/考公/事业编/国企 信息卡（稳定结构；时效信息只做指引不编数字）

create table if not exists public.study_paths (
  id text primary key,
  subject_id text not null references public.subjects (id) on delete cascade,
  kind text not null check (kind in ('kaoyan', 'civil', 'public', 'soe')),
  name text not null,
  description text not null default '',
  exam_subjects jsonb not null default '[]'::jsonb,
  applicable_majors jsonb not null default '[]'::jsonb,
  timeframe jsonb not null default '[]'::jsonb,
  notes text not null default '',
  sort_order integer not null default 0
);

create index if not exists study_paths_subject_idx on public.study_paths (subject_id);

alter table public.study_paths enable row level security;

drop policy if exists "study_paths_select_authenticated" on public.study_paths;
create policy "study_paths_select_authenticated"
  on public.study_paths for select to authenticated using (true);

